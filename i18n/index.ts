import { getLocales } from 'expo-localization';

function getDeviceLang(): 'en' | 'es' | 'ca' {
  const code = getLocales()[0]?.languageCode;
  if (code === 'en') return 'en';
  if (code === 'ca') return 'ca';
  return 'es';
}

